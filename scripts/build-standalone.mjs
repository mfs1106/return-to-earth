/**
 * Produces RETURN-TO-EARTH.html: one self-contained HTML file that can be
 * opened by double-clicking (file://). It inlines the built CSS and JS and
 * turns the favicon into a data URI. No network access is needed at runtime.
 *
 * Run with: npm run build:standalone
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const distDir = path.join(root, 'dist');
const htmlPath = path.join(distDir, 'index.html');

if (!fs.existsSync(htmlPath)) {
  console.error('dist/index.html was not found. Run "npm run build" first.');
  process.exit(1);
}

let html = fs.readFileSync(htmlPath, 'utf8');

function readAssetFromTag(match) {
  if (!match) return null;
  const raw = match[1].replace(/^\.?\//, '');
  const assetPath = path.join(distDir, raw);
  if (!fs.existsSync(assetPath)) {
    throw new Error(`Built asset not found: ${assetPath}`);
  }
  return fs.readFileSync(assetPath, 'utf8');
}

const cssTag = html.match(/<link rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/);
const jsTag = html.match(/<script type="module"[^>]*src="([^"]+)"[^>]*><\/script>/);
if (!cssTag || !jsTag) {
  console.error('Could not find the built CSS/JS tags in dist/index.html.');
  process.exit(1);
}
const css = readAssetFromTag(cssTag);
let js = readAssetFromTag(jsTag);
js = js.replace(/<\/script/gi, '<\\/script');
const safeCss = css.replace(/<\/style/gi, '<\\/style');

html = html.replace(cssTag[0], `<style>${safeCss}</style>`);
html = html.replace(jsTag[0], `<script type="module">${js}</script>`);

// Inline the small favicon so the single file has no remaining local links.
const faviconPath = path.join(root, 'public', 'favicon.svg');
if (fs.existsSync(faviconPath)) {
  const favicon = fs.readFileSync(faviconPath, 'utf8');
  const dataUri = `data:image/svg+xml;base64,${Buffer.from(favicon).toString('base64')}`;
  html = html.replace(/<link rel="icon"[^>]*>/, `<link rel="icon" href="${dataUri}" type="image/svg+xml" />`);
}

const banner = `<!-- RETURN TO EARTH standalone build. Generated by scripts/build-standalone.mjs. -->\n`;
const outputPath = path.join(root, 'RETURN-TO-EARTH.html');
fs.writeFileSync(outputPath, banner + html, 'utf8');

const size = fs.statSync(outputPath).size;
console.log(`Standalone file written: ${outputPath}`);
console.log(`Size: ${(size / 1024 / 1024).toFixed(2)} MB`);
console.log('Open it by double-clicking; it does not need a local server.');
